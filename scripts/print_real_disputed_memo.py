import os
import sys
import json

if hasattr(sys.stdout, "reconfigure"):
    sys.stdout.reconfigure(encoding="utf-8")

REPO_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RESULTS_PATH = os.path.join(REPO_DIR, "data", "offline_model_eval_results.json")

def main():
    print("=" * 110)
    print("ITEM 10: REAL MEMO WITH ACTIVE DISPUTED BANNER (PROD MODEL: claude-haiku-4-5-20251001)")
    print("=" * 110)

    with open(RESULTS_PATH, "r", encoding="utf-8") as f:
        results = json.load(f)

    # First result is Q1 (FIO Section 22 - Disputed provision)
    q1 = results[0]
    print(f"Query ID:   {q1['query_id']}")
    print(f"Title:      {q1['title']}")
    print(f"Model ID:   {q1['model_id']}")
    print(f"Latency:    {q1['latency_sec']:.2f}s")
    print(f"Characters: {q1['memo_length']:,}")
    print("-" * 110)
    print("MEMO TEXT:")
    print("-" * 110)
    print(q1["memo"])
    print("=" * 110)

if __name__ == "__main__":
    main()
