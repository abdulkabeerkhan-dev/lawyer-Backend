r"""
scripts/zilliz/create_collection.py

Creates the Zilliz Cloud collection `judgments_v1` strictly following
docs/antigravity/RULES.md (Rules 16, 20, 22) and docs/ZILLIZ_MIGRATION_PLAN.md §7.

Schema definition:
- chunk_id (VARCHAR 128, primary key, auto_id=False)
- case_key (VARCHAR 64, scalar index for group_by)
- text (VARCHAR 65535, enable_analyzer=True)
- dense (FLOAT_VECTOR 1024, index AUTOINDEX, metric COSINE)
- sparse (SPARSE_FLOAT_VECTOR, BM25 function on text, metric BM25)
- citation, journal, court_code (VARCHAR 128/32/32)
- year, court_level, cited_by_count (INT32)
- section, content_level (VARCHAR 32)
- domain (VARCHAR 32, partition key)
- statutes (ARRAY<VARCHAR 64>, max_capacity 64)
- chunk_hash, embed_model, schema_version, ingested_at (VARCHAR 64/32)

Official docs:
- MilvusClient: https://milvus.io/docs/quickstart.md
- Milvus/Zilliz BM25 Function: https://milvus.io/docs/full-text-search.md
- Milvus/Zilliz Partition Key: https://milvus.io/docs/use-partition-key.md
- Milvus/Zilliz Array DataType: https://milvus.io/docs/array_data_type.md
"""

import os
import sys
import time
import logging
import argparse
from typing import Optional

# Ensure project root in sys.path
SCRIPT_DIR = os.path.dirname(os.path.abspath(__file__))
PROJECT_ROOT = os.path.abspath(os.path.join(SCRIPT_DIR, "..", ".."))
if PROJECT_ROOT not in sys.path:
    sys.path.insert(0, PROJECT_ROOT)

from dotenv import load_dotenv
from pymilvus import (
    MilvusClient,
    CollectionSchema,
    FieldSchema,
    DataType,
    Function,
    FunctionType,
)

LOG_DIR = r"I:\zilliz_work\logs"
os.makedirs(LOG_DIR, exist_ok=True)
logging.basicConfig(
    level=logging.INFO,
    format="%(asctime)s [%(levelname)s] %(message)s",
    handlers=[
        logging.StreamHandler(sys.stdout),
        logging.FileHandler(os.path.join(LOG_DIR, "create_collection.log"), encoding="utf-8"),
    ],
)
logger = logging.getLogger("create_collection")


def build_collection_schema(dim: int = 1024) -> CollectionSchema:
    """Build exact collection schema conforming to spec §7."""
    fields = [
        FieldSchema(
            name="chunk_id",
            dtype=DataType.VARCHAR,
            max_length=128,
            is_primary=True,
            auto_id=False,
            description="Unique deterministic chunk identifier: {case_key}:{section}:{ordinal:03d}",
        ),
        FieldSchema(
            name="case_key",
            dtype=DataType.VARCHAR,
            max_length=64,
            description="Canonical case key: {year}_{journal}_{court_code}_{page}",
        ),
        FieldSchema(
            name="text",
            dtype=DataType.VARCHAR,
            max_length=65535,
            enable_analyzer=True,
            description="Chunk text including contextual metadata header",
        ),
        FieldSchema(
            name="dense",
            dtype=DataType.FLOAT_VECTOR,
            dim=dim,
            description=f"Dense embedding vector ({dim}-d)",
        ),
        FieldSchema(
            name="sparse",
            dtype=DataType.SPARSE_FLOAT_VECTOR,
            description="Sparse BM25 representation generated by function",
        ),
        FieldSchema(
            name="citation",
            dtype=DataType.VARCHAR,
            max_length=128,
            description="Human readable primary citation e.g. 2024 SCMR 14",
        ),
        FieldSchema(
            name="journal",
            dtype=DataType.VARCHAR,
            max_length=32,
            description="Law journal acronym e.g. SCMR, PLD, YLR",
        ),
        FieldSchema(
            name="court_code",
            dtype=DataType.VARCHAR,
            max_length=32,
            description="Standardized court identifier e.g. SC, LHC, SHC",
        ),
        FieldSchema(
            name="year",
            dtype=DataType.INT32,
            description="Decision or publication year",
        ),
        FieldSchema(
            name="court_level",
            dtype=DataType.INT32,
            description="Hierarchical authority rank: 1=SC, 2=FSC, 3=HC, 4=Tribunals, 5=Subordinate",
        ),
        FieldSchema(
            name="cited_by_count",
            dtype=DataType.INT32,
            description="Total incoming citations in the Pakistani case law corpus",
        ),
        FieldSchema(
            name="section",
            dtype=DataType.VARCHAR,
            max_length=32,
            description="Judgment structural section: headnote, facts, arguments, issues, reasoning, holding, order, preamble",
        ),
        FieldSchema(
            name="content_level",
            dtype=DataType.VARCHAR,
            max_length=32,
            description="Source document classification: full_judgment or headnote_only",
        ),
        FieldSchema(
            name="domain",
            dtype=DataType.VARCHAR,
            max_length=32,
            is_partition_key=True,
            description="Primary legal domain partition key (criminal, civil, constitutional, etc.)",
        ),
        FieldSchema(
            name="statutes",
            dtype=DataType.ARRAY,
            element_type=DataType.VARCHAR,
            max_capacity=64,
            max_length=64,
            description="Referenced canonical statute section IDs e.g. CRPC_1898_SEC_497",
        ),
        FieldSchema(
            name="chunk_hash",
            dtype=DataType.VARCHAR,
            max_length=64,
            description="SHA-256 hash of chunk text for idempotency",
        ),
        FieldSchema(
            name="embed_model",
            dtype=DataType.VARCHAR,
            max_length=64,
            description="Model used to embed dense vector",
        ),
        FieldSchema(
            name="schema_version",
            dtype=DataType.VARCHAR,
            max_length=32,
            description="Schema version (v1)",
        ),
        FieldSchema(
            name="ingested_at",
            dtype=DataType.VARCHAR,
            max_length=32,
            description="ISO timestamp of ingestion",
        ),
    ]

    bm25_function = Function(
        name="text_bm25_emb",
        function_type=FunctionType.BM25,
        input_field_names=["text"],
        output_field_names=["sparse"],
    )

    schema = CollectionSchema(
        fields=fields,
        functions=[bm25_function],
        description="Pakistani case law judgments collection with dense & sparse BM25 retrieval",
        enable_dynamic_field=False,
    )
    return schema


def create_collection(
    collection_name: str = "judgments_v1",
    dim: int = 1024,
    recreate: bool = False,
    dry_run: bool = False,
) -> Optional[MilvusClient]:
    """Connect to Zilliz Cloud using MilvusClient and create collection with indexes."""
    load_dotenv(os.path.join(PROJECT_ROOT, ".env"))
    uri = os.environ.get("ZILLIZ_URI")
    token = os.environ.get("ZILLIZ_TOKEN")

    if not uri or not token:
        raise ValueError("ZILLIZ_URI or ZILLIZ_TOKEN missing from .env")

    logger.info(f"Connecting to Zilliz Cloud endpoint...")
    client = MilvusClient(uri=uri, token=token)

    schema = build_collection_schema(dim=dim)

    if dry_run:
        logger.info(f"[DRY-RUN] Schema verified successfully with {len(schema.fields)} fields and {len(schema.functions)} functions.")
        logger.info(f"[DRY-RUN] Target collection: {collection_name} (dim={dim})")
        return client

    # Check existing collection
    if client.has_collection(collection_name):
        if not recreate:
            raise RuntimeError(
                f"Collection '{collection_name}' already exists. Pass --recreate to drop and recreate."
            )
        logger.warning(f"Dropping existing collection '{collection_name}'...")
        client.drop_collection(collection_name)
        time.sleep(2)

    logger.info("Preparing index parameters...")
    index_params = client.prepare_index_params()
    index_params.add_index(
        field_name="dense",
        metric_type="COSINE",
        index_type="AUTOINDEX",
    )
    index_params.add_index(
        field_name="sparse",
        metric_type="BM25",
        index_type="SPARSE_INVERTED_INDEX",
    )
    index_params.add_index(
        field_name="case_key",
        index_name="idx_case_key",
    )

    logger.info(f"Creating collection '{collection_name}' with schema and indexes...")
    client.create_collection(
        collection_name=collection_name,
        schema=schema,
        index_params=index_params,
    )

    logger.info(f"Collection '{collection_name}' created and indexed successfully!")
    return client


def main():
    parser = argparse.ArgumentParser(description="Create Zilliz judgments collection")
    parser.add_argument("--collection", default="judgments_v1", help="Collection name")
    parser.add_argument("--dim", type=int, default=1024, help="Dense vector dimension")
    parser.add_argument("--recreate", action="store_true", help="Force recreate collection")
    parser.add_argument("--dry-run", action="store_true", help="Dry run schema check")

    args = parser.parse_args()
    create_collection(
        collection_name=args.collection,
        dim=args.dim,
        recreate=args.recreate,
        dry_run=args.dry_run,
    )


if __name__ == "__main__":
    main()
