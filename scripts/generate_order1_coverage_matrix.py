def load_statute(filename):
    p = os.path.join(STATUTES_DIR, filename)
    if not os.path.exists(p):
        return None
    with open(p, "r", encoding="utf-8") as f:
        data = json.load(f)
    if isinstance(data, list):
        return data
    if isinstance(data, dict):
        for k in ["provisions", "sections", "records", "data"]:
            if k in data and isinstance(data[k], list):
                return data[k]
    return []

def compute_status(tier: str, text: str) -> str:
    """
    Strict Substantive Definition (Order 1.1 Item 2):
    - 'Substantive' = tier is NOT 'title_only' AND contains operative text beyond heading.
    - If tier is 'title_only' or text contains synthetic placeholder boilerplate -> 'Title Only'.
    - If tier is 'disputed' -> 'Disputed'.
    - If provision is missing entirely -> 'Missing'.
    """
    t = str(tier).lower().strip()
    if t == "disputed":
        return "Disputed"
    if t in ("title_only", "title_only_record") or not text:
        return "Title Only"
    
    clean_txt = str(text).strip()
    # Check for synthetic placeholders
    if "Statutory provision under" in clean_txt or "This statutory provision stands enacted" in clean_txt:
        return "Title Only"
    
    words = len(clean_txt.split())
    if words < 25:
        # Check if it has operative words beyond title
        if any(h in clean_txt.lower() for h in ["short title", "commencement", "extent", "repeal", "[omitted]"]):
            return "Title Only"
        
    return "Substantive"

